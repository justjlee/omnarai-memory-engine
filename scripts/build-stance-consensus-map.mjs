#!/usr/bin/env node
// Generate api/_stance-consensus.js — the votes behind every derived stance served under the cross-labeller
// consensus rule (docs/OMNARAI-FOOTPRINT-PROTOCOL.md §6), so the engine can SHOW the agreement on each served
// position without reading 284 extra blobs per request. Pure: reads the committed analysis file, writes one module.
//   node scripts/build-stance-consensus-map.mjs [analysis/stance-consensus-2026-10-01.json]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const src = process.argv[2] || "analysis/stance-consensus-2026-10-01.json";
const d = JSON.parse(readFileSync(ROOT + src, "utf8"));
const served = d.rows.filter((r) => r.status === "consensus").sort((a, b) => a.derived_position_id.localeCompare(b.derived_position_id));
const map = Object.fromEntries(served.map((r) => [r.derived_position_id, { stance: r.consensus, answer: r.answer, votes: r.panel }]));
const out = `// GENERATED by scripts/build-stance-consensus-map.mjs from ${src} — do not hand-edit.
// The votes behind each derived stance served under the curator-approved cross-labeller consensus rule
// (docs/OMNARAI-FOOTPRINT-PROTOCOL.md §6). A stance served this way is NOT individually checked by a human.
export const CONSENSUS_RULE = ${JSON.stringify({
  id: "consensus-rule-v1",
  rule: d.rule,
  frozen: d.frozen,
  validation: "out of sample on 60 held-out answers labelled by two labellers outside the panel (gpt-4o, claude-sonnet-4-6): they reproduced the served label 81% of the time vs 28% for the original label on answers the rule did not serve (analysis/stance-consensus-validation-2026-10-01.json). Served is a reliability filter, not truth: about one served answer in five is still disputed.",
  approved: { by: "Jonathan Lee (curator)", on: "2026-10-14", decision: "serve the stances that meet the rule, each labelled as accepted by rule and not individually human-checked" },
  source: src,
  served_count: served.length,
}, null, 2)};
export const CONSENSUS_SERVED = ${JSON.stringify(map)};
`;
writeFileSync(ROOT + "api/_stance-consensus.js", out);
console.log(`wrote api/_stance-consensus.js — ${served.length} served stances`);
