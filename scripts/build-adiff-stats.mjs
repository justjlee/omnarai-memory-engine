// build-adiff-stats.mjs — SINGLE SOURCE OF TRUTH for the architecture-differential
// finding's numbers (HANDOFF-ADIFF-2026-08 §2.B "Stat consistency").
//
// The August stat-drift audit's defect class was hand-copied numbers drifting across
// surfaces. Fix at the root: every surface that shows these numbers derives them, here,
// from the ONE primary file — the preregistered eval's aggregate — and never by hand.
//
//   PRIMARY (append-only, never modified):
//     huggingface/utility/utility-prereg-aggregate.json   (analyzed 2026-07-15)
//   GENERATED:
//     public/data/adiff-stats.json      <- served CORS-open at engine.omnarai.org/data/
//                                          (the runtime source the flagship + landing pages fetch)
//     huggingface/utility-evidence-v2.md <- the GRADIENT block between the ADIFF-STATS markers
//
// Usage:
//   node scripts/build-adiff-stats.mjs           # regenerate all surfaces from the primary
//   node scripts/build-adiff-stats.mjs --check    # exit 1 if any surface has drifted (deploy gate)
//
// Tier/effect are DERIVED from the numbers, not hardcoded, so the file can never assert a
// direction the data don't support.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRIMARY = path.join(ROOT, "huggingface/utility/utility-prereg-aggregate.json");
const OUT_JSON = path.join(ROOT, "public/data/adiff-stats.json");
const HF_CARD = path.join(ROOT, "huggingface/utility-evidence-v2.md");
const MARK_A = "<!-- ADIFF-STATS:START (generated by scripts/build-adiff-stats.mjs — do not hand-edit) -->";
const MARK_B = "<!-- ADIFF-STATS:END -->";
const CHECK = process.argv.includes("--check");

const ORDER = ["GPT-4o", "Gemini", "Grok", "DeepSeek", "Claude"]; // gradient reading order

function tierOf(T, P, pTwoSided) {
  // significance at family alpha; direction from the win split.
  if (pTwoSided < 0.05 && T > P) return { tier: "positive", effect: "improved" };
  if (pTwoSided < 0.05 && P > T) return { tier: "negative", effect: "degraded" };
  return { tier: "null", effect: "no effect" };
}

function build() {
  const agg = JSON.parse(fs.readFileSync(PRIMARY, "utf8"));
  const consumers = ORDER.map((name) => {
    const c = agg.consumers[name];
    if (!c) throw new Error(`consumer ${name} missing from primary aggregate`);
    const { T, P, decided, p_two_sided, p_holm } = c.pooled;
    const { tier, effect } = tierOf(T, P, p_two_sided);
    const registeredPositive = /H1/.test(c.registered_prediction);
    // H1 predicts positive; H2 predicts "no advantage" (null OR reverse both = no advantage).
    const confirmed = registeredPositive ? tier === "positive" : tier !== "positive";
    return {
      model: name,
      registered_prediction: c.registered_prediction,
      registered_hypothesis: registeredPositive ? "H1" : "H2",
      tier, effect,
      T, P, decided,
      win_rate_treatment: decided ? +(T / decided).toFixed(3) : null,
      p_two_sided, p_holm,
      h3_survives_paraphrase: c.h3_survives_paraphrase,
      effect_at_both_caps: c.effect_at_both_caps,
      inter_judge_agreement: c.inter_judge_agreement,
      confirmed,
      verdict: c.verdict,
    };
  });
  const confirmedCount = consumers.filter((c) => c.confirmed).length;
  return {
    _about:
      "Architecture-differential utility finding — SINGLE SOURCE OF TRUTH. Generated by " +
      "scripts/build-adiff-stats.mjs from huggingface/utility/utility-prereg-aggregate.json " +
      "(the preregistered eval's primary aggregate). DO NOT HAND-EDIT. The flagship page, the " +
      "landing-page link, and the HuggingFace card all derive their numbers from this file so " +
      "they cannot drift (the August stat-drift defect class, fixed at the root).",
    generated_at: new Date().toISOString(),
    source: "huggingface/utility/utility-prereg-aggregate.json",
    preregistration: agg.preregistration,
    run_date: "2026-07-15",
    family_alpha: agg.family_alpha,
    metric:
      "T = treatment (Atlas-exposed revision) wins, P = placebo (self-reflection) wins, over " +
      "decided majority-vote instances. One-sided exact binomial + Holm across 5 consumers.",
    registered_predictions_total: consumers.length,
    registered_predictions_confirmed: confirmedCount,
    all_confirmed: confirmedCount === consumers.length,
    gradient: consumers.map((c) => ({ model: c.model, effect: c.effect, tier: c.tier })),
    consumers,
    task_type_breakdown: {
      status: "see analysis/adiff-tasktype-2026-08.md (Work Item A)",
      note:
        "Per-task-type breakdown of the Claude degradation lives in the analysis/ file; its " +
        "mechanism reading is curator-gated and NOT rendered here.",
    },
    refs: {
      evidence: "utility-evidence-v2.md",
      preregistration: "docs/utility-eval-preregistration.md",
      claim: "claims.json#divergence-improves-reasoning",
    },
  };
}

function fmtHolm(p) {
  if (p < 1e-6) return "<10⁻⁶";
  if (p >= 0.1) return p.toFixed(2).replace(/0$/, "");
  return p.toPrecision(2);
}
function hfBlock(stats) {
  const rows = stats.consumers
    .map((c) => {
      const h1 = c.registered_hypothesis === "H1";
      const h3 = h1 ? (c.h3_survives_paraphrase ? "✓ 3/3" : "✗") : "—";
      const caps = h1 ? (c.effect_at_both_caps ? "✓" : "✗") : "—";
      return `| **${c.model}** | ${c.registered_prediction} | **${c.T}–${c.P}** | ${fmtHolm(c.p_holm)} | ${h3} | ${caps} | ${c.effect} — ${c.confirmed ? "prediction confirmed" : "NOT confirmed"} |`;
    })
    .join("\n");
  return [
    MARK_A,
    ``,
    `**${stats.registered_predictions_confirmed} / ${stats.registered_predictions_total} registered predictions confirmed.** Preregistration ${stats.preregistration}; run ${stats.run_date}.`,
    ``,
    `| Consumer | Registered prediction | Result (T–P, pooled) | Holm-adj. p | H3 (≥2/3 paraphrases) | Both caps | Effect / status |`,
    `|---|---|---|---|---|---|---|`,
    rows,
    ``,
    `*T = treatment (Atlas-exposed revision) wins, P = placebo (self-reflection) wins, over decided majority-vote instances; one-sided exact binomial + Holm across the 5 consumers. **These numbers are generated from the primary aggregate (\`${stats.source}\`) by \`scripts/build-adiff-stats.mjs\` — not hand-copied.** The same source feeds the flagship page (\`/findings/architecture-differential\`) and the landing-page link, so all three surfaces cannot drift.*`,
    MARK_B,
  ].join("\n");
}

function spliceCard(text, block) {
  const i = text.indexOf(MARK_A);
  const j = text.indexOf(MARK_B);
  if (i === -1 || j === -1) return null; // markers absent — card not wired yet
  return text.slice(0, i) + block + text.slice(j + MARK_B.length);
}

const stats = build();
const jsonStr = JSON.stringify(stats, null, 2) + "\n";
// Ignore the volatile generated_at when comparing for drift.
const stripTime = (s) => s.replace(/"generated_at":\s*"[^"]*"/, '"generated_at":"_"');

if (CHECK) {
  let drift = [];
  const cur = fs.existsSync(OUT_JSON) ? fs.readFileSync(OUT_JSON, "utf8") : "";
  if (stripTime(cur) !== stripTime(jsonStr)) drift.push(`public/data/adiff-stats.json out of date`);
  if (fs.existsSync(HF_CARD)) {
    const cardCur = fs.readFileSync(HF_CARD, "utf8");
    const want = spliceCard(cardCur, hfBlock(stats));
    if (want !== null && want !== cardCur) drift.push(`huggingface/utility-evidence-v2.md ADIFF-STATS block out of date`);
  }
  if (drift.length) {
    console.error("ADIFF stat drift:\n  - " + drift.join("\n  - ") + "\nRun: node scripts/build-adiff-stats.mjs");
    process.exit(1);
  }
  console.log("adiff-stats: all surfaces consistent with the primary aggregate.");
  process.exit(0);
}

fs.writeFileSync(OUT_JSON, jsonStr);
console.log(`wrote ${path.relative(ROOT, OUT_JSON)} (${stats.registered_predictions_confirmed}/${stats.registered_predictions_total} confirmed)`);
if (fs.existsSync(HF_CARD)) {
  const cardCur = fs.readFileSync(HF_CARD, "utf8");
  const next = spliceCard(cardCur, hfBlock(stats));
  if (next === null) {
    console.log(`note: ${path.relative(ROOT, HF_CARD)} has no ADIFF-STATS markers yet — add them to wire the HF card to this source.`);
  } else if (next !== cardCur) {
    fs.writeFileSync(HF_CARD, next);
    console.log(`updated ADIFF-STATS block in ${path.relative(ROOT, HF_CARD)}`);
  } else {
    console.log(`${path.relative(ROOT, HF_CARD)} already current`);
  }
}
console.log("\ngradient:");
for (const c of stats.consumers) console.log(`  ${c.model.padEnd(9)} ${c.T}-${c.P}  ${c.effect.padEnd(10)} [${c.tier}] ${c.registered_hypothesis} ${c.confirmed ? "confirmed" : "NOT"}`);
